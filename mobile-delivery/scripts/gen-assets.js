// Generates src/lib/assetMap.js: web public path -> bundled require().
// Files under assets/web/ mirror frontend/public/ paths. Re-run after adding assets.
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..', 'assets', 'web');
const out = [];
const walk = (dir) => {
  for (const f of fs.readdirSync(dir)) {
    const p = path.join(dir, f);
    if (fs.statSync(p).isDirectory()) walk(p);
    else if (/\.(png|jpe?g|webp|gif)$/i.test(f)) {
      const rel = path.relative(root, p).split(path.sep).join('/');
      out.push(`  ${JSON.stringify('/' + rel)}: require(${JSON.stringify('../../assets/web/' + rel)}),`);
    }
  }
};
walk(root);
fs.writeFileSync(
  path.join(__dirname, '..', 'src', 'lib', 'assetMap.js'),
  `// AUTO-GENERATED by scripts/gen-assets.js — do not edit.\n/* eslint-disable */\nexport default {\n${out.sort().join('\n')}\n};\n`
);
console.log(`assetMap: ${out.length} files`);
